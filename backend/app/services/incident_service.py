    def list_incidents(
        self,
        city: Optional[str] = None,
        severity: Optional[str] = None,
        status: Optional[str] = None,
        verified_only: bool = False
    ) -> List[Incident]:
        """Filter incidents by city, severity, status, or verification state."""
        results = list(self._incidents.values())
        if city:
            results = [i for i in results if i.city.lower() == city.lower()]
        if severity:
            results = [i for i in results if i.severity.upper() == severity.upper()]
        if status:
            results = [i for i in results if i.status == status]
        if verified_only:
            results = [i for i in results if i.is_verified]
        
        # Sort by updated_at descending
        results.sort(key=lambda x: x.updated_at, reverse=True)
        return results

    def get_incident(self, incident_id: str) -> Optional[Incident]:
        for k, v in self._incidents.items():
            if k.lower() == incident_id.lower():
                return v
        return None

    def verify_incident(self, incident_id: str, req: VerifyIncidentRequest) -> Incident:
        inc = self.get_incident(incident_id)
        if not inc:
            raise KeyError(f"Incident {incident_id} not found.")

        now = get_utc_now()
        inc.updated_at = now
        time_str = now.strftime("%H:%M UTC")

        if req.decision == "verified":
            inc.is_verified = True
            inc.status = "verified"
            inc.timeline_updates.append({
                "time": time_str,
                "event": f"Verified by {req.officer_name} (Badge #{req.officer_badge}). Notes: {req.notes}"
            })
            self._audit_log.append({
                "timestamp": now.isoformat(),
                "officer_name": req.officer_name,
                "officer_badge": req.officer_badge,
                "action": "VERIFY_INCIDENT",
                "incident_id": inc.id,
                "details": f"Verified incident: {req.notes}"
            })
        else:
            inc.status = "dismissed"
            inc.is_verified = False
            inc.timeline_updates.append({
                "time": time_str,
                "event": f"Dismissed as false positive by {req.officer_name}. Reason: {req.notes}"
            })
            self._audit_log.append({
                "timestamp": now.isoformat(),
                "officer_name": req.officer_name,
                "officer_badge": req.officer_badge,
                "action": "DISMISS_INCIDENT",
                "incident_id": inc.id,
                "details": f"Dismissed observation: {req.notes}"
            })

        return inc

    def create_advisory(self, incident_id: str, req: CreateAdvisoryRequest) -> Incident:
        inc = self.get_incident(incident_id)
        if not inc:
            raise KeyError(f"Incident {incident_id} not found.")

        now = get_utc_now()
        inc.updated_at = now
        inc.severity = req.severity
        inc.status = "advisory_published"
        inc.is_verified = True

        inc.advisory = AdvisoryInfo(
            headline=req.headline,
            public_action=req.public_action,
            affected_radius_km=req.affected_radius_km,
            published_by=req.officer_name,
            published_at=now
        )

        inc.timeline_updates.append({
            "time": now.strftime("%H:%M UTC"),
            "event": f"Public Advisory published: '{req.headline}' by {req.officer_name}"
        })

        self._audit_log.append({
            "timestamp": now.isoformat(),
            "officer_name": req.officer_name,
            "officer_badge": "MH-PN-2041",
            "action": "PUBLISH_ADVISORY",
            "incident_id": inc.id,
            "details": f"Broadcast advisory to {req.affected_radius_km} km radius: {req.headline}"
        })

        return inc

    def resolve_incident(self, incident_id: str, req: ResolveIncidentRequest) -> Incident:
        inc = self.get_incident(incident_id)
        if not inc:
            raise KeyError(f"Incident {incident_id} not found.")

        now = get_utc_now()
        inc.updated_at = now
        inc.severity = "GREEN"
        inc.status = "resolved"

        if inc.advisory:
            inc.advisory.headline = f"{inc.advisory.headline} — RESOLVED"
            inc.advisory.public_action = f"Situation normalized. {req.resolution_notes}"

        inc.timeline_updates.append({
            "time": now.strftime("%H:%M UTC"),
            "event": f"Marked RESOLVED by {req.officer_name}. Notes: {req.resolution_notes}"
        })

        self._audit_log.append({
            "timestamp": now.isoformat(),
            "officer_name": req.officer_name,
            "officer_badge": "MH-PN-2041",
            "action": "RESOLVE_INCIDENT",
            "incident_id": inc.id,
            "details": f"Hazard resolved: {req.resolution_notes}"
        })

        return inc

    def get_public_nearby_advisories(
        self,
        lat: Optional[float] = None,
        lng: Optional[float] = None,
        city: Optional[str] = None,
        radius_km: float = 15.0
    ) -> Dict[str, Any]:
        """Fetch verified public advisories and calculate approximate distance."""
        active = [
            i for i in self._incidents.values()
            if i.is_verified and i.status in ["verified", "advisory_published", "resolved"]
        ]

        if city:
            active = [i for i in active if i.city.lower() == city.lower()]

        items = []
        for inc in active:
            dist = None
            if lat is not None and lng is not None:
                dist = haversine_distance_km(lat, lng, inc.lat, inc.lng)
            
            items.append({
                "id": inc.id,
                "incident_id": inc.id,
                "title": inc.title,
                "city": inc.city,
                "locality": inc.locality,
                "state": inc.state,
                "lat": inc.lat,
                "lng": inc.lng,
                "severity": inc.severity,
                "status": inc.status,
                "distance_km": dist,
                "reported_at": inc.reported_at.isoformat(),
                "updated_at": inc.updated_at.isoformat(),
                "advisory": inc.advisory.model_dump() if inc.advisory else None,
                "is_demonstration": True
            })

        if lat is not None and lng is not None:
            # Sort by distance
            items.sort(key=lambda x: x["distance_km"] if x["distance_km"] is not None else 9999)

        # Overall safety score: Red -> RED status, Yellow -> YELLOW status, else GREEN
        has_red = any(it["severity"] == "RED" and it["status"] != "resolved" for it in items)
        has_yellow = any(it["severity"] == "YELLOW" and it["status"] != "resolved" for it in items)
        
        overall_status = "RED" if has_red else "YELLOW" if has_yellow else "GREEN"

        return {
            "overall_status": overall_status,
            "overall_city_status": overall_status,
            "selected_city": city,
            "user_coords": {"lat": lat, "lng": lng} if lat and lng else None,
            "active_count": len(items),
            "active_advisories_count": len([it for it in items if it.get("advisory")]),
            "incidents": items,
            "distance_clarification": "Approximate straight-line distance (Haversine formula)",
            "disclaimer": "DEMONSTRATION SAFETY DATA: Simulated records for public testing in India."
        }

    def get_audit_log(self) -> List[Dict[str, Any]]:
        return self._audit_log


